"""KUKO WAY "Movement Within": two artistic QR concepts built around a real code.

The QR symbol is generated by segno from the exact URL (version 6, level H; its
only alignment pattern sits bottom-right, so the centre is free for the figure).
Every module position comes from segno's matrix. Finder patterns, separators,
timing patterns, the alignment pattern, format information and the dark module
are always drawn solid in charcoal and never covered by the figure or by lines.

The person comes from the reference sasho-qr-code-new-2.jpg (segmented with
generate_forest_qr.person_mask) and is restyled in the KUKO WAY palette.

Concept A, "negative space": the figure is the code's light space, drawn in fine
  charcoal line work over a soft moss tone. The dark data modules run up to the
  body's own outline (a hairline of air) and are clipped along it, and sage
  fascial lines run over the body.
Concept B, "flow": the body's movement ripples outward through the code as
  fascial contour rings (iso-distance lines of the silhouette) running through
  the light space, and two spiral fascial lines cross the body and continue into
  the pattern. Modules soften to rounded 0.8-module tiles near the body and
  return to full squares farther out. Rings and outer lines are moss, which stays
  on the light side of a scanner's threshold even across a module centre.

Usage:  python movement_within.py
        -> out/movement-within-A.png, out/movement-within-B.png   (2400x3000)
           out/movement-within-A-1200.png, out/movement-within-B-1200.png
           out/movement-within-compare.png                         (side by side)
"""
from __future__ import annotations

import math
from pathlib import Path

import cv2
import numpy as np
import segno
from PIL import Image, ImageDraw, ImageFont

import generate_forest_qr as forest

HERE = Path(__file__).resolve().parent
OUT = HERE / "out"
FONTS = HERE.parent / "platform" / "app" / "fonts"
URL = "https://daily-trainer-app.vercel.app/"

# canvas: 4:5 card, symbol centred in the upper part, type below
W, H = 2400, 3000
M = 48                                  # module size, px
QUIET = 4
SS = 2                                  # supersampling for vector layers
WEB_R = 0.18                            # fascial-web pore radius, modules
KNOCK_R = 0.2                           # line gap at light module centres (concept B), modules
WEB_A, WEB_B = 0.35, 0.35               # pore strength per concept (subtle; restores data under the body)

IVORY = (245, 240, 230)                 # warm ivory
CHARCOAL = (30, 31, 28)                 # deep charcoal (structural patterns, line work)
FOREST = (40, 56, 44)                   # dark forest green (data modules)
SAGE = (125, 139, 114)                  # #7D8B72
MOSS = (170, 179, 156)                  # #AAB39C
RING = (148, 158, 136)                  # sage-moss for contour rings (luminance ~155: reads light)
RAMP = [(0.0, CHARCOAL), (0.3, FOREST), (0.62, SAGE), (0.82, MOSS), (1.0, IVORY)]

# figure: reference crop (src px, after forest.CROP_Y) and placement in modules
FIG_BOX = (374, 290, 671, 788)          # x0, y0, x1, y1 in the 1024x1024 reference
FIG_ROWS = 23.0                         # figure height in modules
FIG_TOP = 8.6                           # top row of the figure (stays clear of timing row 6)

# fascial pathways in the reference's 2x crop coordinates (594 x 996)
LINES_BODY = {
    # spiral line: jaw -> across the chest -> opposite hip -> knee -> ankle
    "spiral_r": [(395, 140), (330, 300), (230, 420), (180, 560), (120, 640), (70, 690),
                 (60, 740), (70, 830), (100, 900), (110, 950)],
    "spiral_l": [(175, 215), (300, 380), (420, 470), (465, 600), (510, 650), (530, 690),
                 (520, 720), (515, 820), (505, 890), (500, 950)],
    # front line: neck -> jaw -> cheek -> temple, where the hands work
    "jaw": [(285, 235), (300, 190), (350, 175), (400, 170), (440, 160), (440, 110), (410, 60)],
}
# concept B: the spirals enter from beyond the body and leave into the pattern
TAILS = {
    "spiral_r": ([(560, -260), (520, -120), (450, 40)], [(110, 1010), (40, 1090), (-160, 1160)]),
    "spiral_l": ([(-200, -80), (-60, 60), (90, 160)], [(500, 1010), (580, 1090), (780, 1160)]),
}


def qr_matrix():
    qr = segno.make(URL, error="h", version=6, boost_error=False)
    return qr, [[bool(v) for v in row] for row in qr.matrix]


def functional(r, c, n):
    """Structural modules: finders + separators, timing, alignment, format info."""
    for fr, fc in ((0, 0), (0, n - 8), (n - 8, 0)):
        if fr <= r < fr + 8 and fc <= c < fc + 8:
            return True
    if r == 6 or c == 6:
        return True
    if n - 9 <= r <= n - 5 and n - 9 <= c <= n - 5:          # alignment (v6 centre 34,34)
        return True
    if (r == 8 and (c <= 8 or c >= n - 8)) or (c == 8 and (r <= 8 or r >= n - 8)):
        return True
    return False


def in_finder(r, c, n):
    return any(fr <= r < fr + 8 and fc <= c < fc + 8 for fr, fc in ((0, 0), (0, n - 8), (n - 8, 0)))


class Layout:
    def __init__(self, n):
        self.n = n
        self.ox = (W - n * M) // 2
        self.oy = 150 + QUIET * M
        x0, y0, x1, y1 = FIG_BOX
        self.s = FIG_ROWS * M / (y1 - y0)                       # reference px -> canvas px
        self.fx = W / 2 - (x1 - x0) * self.s / 2
        self.fy = self.oy + FIG_TOP * M

    def centre(self, r, c):
        return self.ox + (c + .5) * M, self.oy + (r + .5) * M

    def fig_pt(self, p):
        """2x-crop reference point -> canvas px."""
        return self.fx + p[0] / 2 * self.s, self.fy + p[1] / 2 * self.s


def load_figure(lay):
    """Reference figure (RGB) and its mask, warped onto the canvas."""
    src = np.array(Image.open(forest.SRC).convert("RGB"))[forest.CROP_Y:forest.CROP_Y + 1024]
    mask = forest.person_mask(src).astype(np.float32)
    x0, y0 = FIG_BOX[:2]
    A = np.float32([[lay.s, 0, lay.fx - x0 * lay.s], [0, lay.s, lay.fy - y0 * lay.s]])
    rgb = cv2.warpAffine(src, A, (W, H), flags=cv2.INTER_CUBIC, borderValue=IVORY).astype(np.float32)
    m = cv2.warpAffine(cv2.GaussianBlur(mask, (5, 5), 0), A, (W, H), flags=cv2.INTER_LINEAR)
    # the reference has a white sticker band around the body; drawing stops at the
    # body's own ink outline, so that band becomes negative space / air instead of a halo
    band = int(round(9 * lay.s)) | 1
    body = cv2.erode((m > .5).astype(np.uint8), cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (band, band)))
    sticker = (rgb.min(2) > 200) & (m > .5)
    body = (body > 0) & ~sticker
    body = cv2.morphologyEx(body.astype(np.uint8), cv2.MORPH_OPEN, np.ones((3, 3), np.uint8))
    return rgb, np.clip(m, 0, 1), cv2.GaussianBlur(body.astype(np.float32), (3, 3), 0)


def ramp(lum):
    xs = [p for p, _ in RAMP]
    return np.stack([np.interp(lum, xs, [c[i] for _, c in RAMP]) for i in range(3)], -1)


def catmull(points, steps=24):
    """Smooth curve through points (Catmull-Rom), canvas px."""
    pts = [points[0]] + list(points) + [points[-1]]
    out = []
    for i in range(1, len(pts) - 2):
        p0, p1, p2, p3 = map(np.array, pts[i - 1:i + 3])
        for t in np.linspace(0, 1, steps, endpoint=False):
            out.append(0.5 * ((2 * p1) + (-p0 + p2) * t + (2 * p0 - 5 * p1 + 4 * p2 - p3) * t * t
                              + (-p0 + 3 * p1 - 3 * p2 + p3) * t ** 3))
    out.append(np.array(points[-1]))
    return [tuple(p) for p in out]


def draw_lines(lay, curves, width, color, ss=SS):
    """Fascial lines as an alpha layer (float, W x H) plus their colour."""
    img = Image.new("L", (W * ss, H * ss), 0)
    d = ImageDraw.Draw(img)
    for pts in curves:
        path = [(x * ss, y * ss) for x, y in catmull([lay.fig_pt(p) for p in pts])]
        d.line(path, fill=255, width=int(width * ss), joint="curve")
        for p in (path[0], path[-1]):
            r = width * ss / 2
            d.ellipse([p[0] - r, p[1] - r, p[0] + r, p[1] + r], fill=255)
    return np.asarray(img.resize((W, H), Image.LANCZOS), np.float32) / 255


def capsule(cx, cy, length, width, angle, steps=10):
    """Polygon of a rounded capsule centred at (cx, cy)."""
    r = width / 2
    half = max(length / 2 - r, 0)
    ca, sa = math.cos(angle), math.sin(angle)
    pts = []
    for end, a0 in ((half, -math.pi / 2), (-half, math.pi / 2)):
        for k in range(steps + 1):
            a = a0 + math.pi * k / steps
            x, y = end + r * math.cos(a), r * math.sin(a)
            pts.append((cx + x * ca - y * sa, cy + x * sa + y * ca))
    return pts


def draw_structure(d, lay, matrix, ss=SS):
    """Finder patterns (rounded 7/5/3) + other structural modules, solid charcoal."""
    n = lay.n
    u = M * ss
    for r in range(n):
        for c in range(n):
            if functional(r, c, n) and not in_finder(r, c, n) and matrix[r][c]:
                x, y = (lay.ox + c * M) * ss, (lay.oy + r * M) * ss
                d.rectangle([x, y, x + u - 1, y + u - 1], fill=CHARCOAL)
    for fr, fc in ((0, 0), (0, n - 7), (n - 7, 0)):
        x, y = (lay.ox + fc * M) * ss, (lay.oy + fr * M) * ss
        # gentle rounding only: OpenCV's finder check fails above ~0.3-module radii
        d.rounded_rectangle([x, y, x + 7 * u - 1, y + 7 * u - 1], radius=u * 0.28, fill=CHARCOAL)
        d.rounded_rectangle([x + u, y + u, x + 6 * u - 1, y + 6 * u - 1], radius=u * 0.18, fill=IVORY)
        d.rounded_rectangle([x + 2 * u, y + 2 * u, x + 5 * u - 1, y + 5 * u - 1], radius=u * 0.15,
                            fill=CHARCOAL)


def typography(img, lay):
    d = ImageDraw.Draw(img)
    serif = ImageFont.truetype(str(FONTS / "dm-serif-display-latin.woff2"), 74)
    sans = ImageFont.truetype(str(FONTS / "manrope-latin.woff2"), 24)
    y0 = lay.oy + (lay.n + QUIET) * M
    for text, font, track, y, col in (("KUKO WAY", serif, 22, y0 + 110, CHARCOAL),
                                      ("MOVEMENT WITHIN", sans, 9, y0 + 222, SAGE)):
        widths = [d.textlength(ch, font=font) for ch in text]
        x = W / 2 - (sum(widths) + track * (len(text) - 1)) / 2
        for ch, w in zip(text, widths):
            d.text((x, y), ch, font=font, fill=col)
            x += w + track


def module_layer(lay, matrix, keep, shape):
    """Dark data modules as an alpha layer; shape(r, c, cx, cy) -> polygon or None."""
    img = Image.new("L", (W * SS, H * SS), 0)
    d = ImageDraw.Draw(img)
    for r in range(lay.n):
        for c in range(lay.n):
            if not matrix[r][c] or functional(r, c, lay.n):
                continue
            cx, cy = lay.centre(r, c)
            if not keep(cx, cy):
                continue
            poly = shape(r, c, cx, cy)
            if poly:
                d.polygon([(x * SS, y * SS) for x, y in poly], fill=255)
    return np.asarray(img.resize((W, H), Image.LANCZOS), np.float32) / 255


def compose(base, layers):
    out = base.astype(np.float32)
    for alpha, color in layers:
        a = alpha[..., None]
        col = color if isinstance(color, np.ndarray) else np.array(color, np.float32)
        out = out * (1 - a) + col * a
    return out


def fascial_web(arr, lay, matrix, zone, strength):
    """Give the figure back its data as a fine fascial web.

    Under the figure zone, every module centre gets a soft tonal pore: darker than
    the drawing for dark modules, lighter for light ones. Up close it reads as a
    mesh texture in skin and cloth; a scanner reads the module values."""
    field = np.zeros((H, W), np.float32)
    for r in range(lay.n):
        for c in range(lay.n):
            cx, cy = lay.centre(r, c)
            if zone[int(cy), int(cx)] > 0:
                cv2.circle(field, (int(cx), int(cy)), int(M * WEB_R), -1.0 if matrix[r][c] else 1.0, -1)
    field = cv2.GaussianBlur(field, (0, 0), M * 0.09) * zone
    dark = np.clip(-field, 0, 1)[..., None] * strength
    light = np.clip(field, 0, 1)[..., None] * strength
    ink = np.array(CHARCOAL, np.float32)
    ivory = np.array(IVORY, np.float32)
    return arr * (1 - dark) + ink * dark + (ivory - arr * (1 - dark) - ink * dark) * light


def finish(arr, lay, matrix):
    img = Image.fromarray(np.clip(arr, 0, 255).round().astype(np.uint8))
    over = Image.new("RGBA", (W * SS, H * SS), (0, 0, 0, 0))
    draw_structure(ImageDraw.Draw(over), lay, matrix)
    over = over.resize((W, H), Image.LANCZOS)
    img.paste(over, (0, 0), over)
    typography(img, lay)
    return img


def concept_a(lay, matrix, fig, mask, body):
    """Figure as the code's light space: dark modules meet the body's own outline."""
    sil = (body > .5).astype(np.uint8)
    gap = int(M * 0.12) | 1                                            # hairline air at the contour
    space = cv2.dilate(sil, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (gap, gap)))
    space_f = cv2.GaussianBlur(space.astype(np.float32), (3, 3), 0)

    def square(r, c, cx, cy):
        h = M * 0.5
        return [(cx - h, cy - h), (cx + h, cy - h), (cx + h, cy + h), (cx - h, cy + h)]

    mods = module_layer(lay, matrix, lambda cx, cy: True, square) * (1 - space_f)

    lum = fig @ np.array([0.299, 0.587, 0.114], np.float32)
    tone = np.clip((235 - lum) / 200, 0, 1) * 0.42                       # soft moss shading
    edges = cv2.adaptiveThreshold(lum.astype(np.uint8), 255, cv2.ADAPTIVE_THRESH_MEAN_C,
                                  cv2.THRESH_BINARY_INV, 15, 9)
    ink = np.maximum(cv2.GaussianBlur(edges.astype(np.float32) / 255, (3, 3), 0) * .85,
                     np.clip((70 - lum) / 50, 0, 1))                      # outlines + darkest accents
    lines = draw_lines(lay, LINES_BODY.values(), 0.15 * M, SAGE) * space_f

    base = np.full((H, W, 3), IVORY, np.float32)
    arr = compose(base, [(mods, FOREST), (tone * body, MOSS), (ink * body, CHARCOAL), (lines, SAGE)])
    arr = fascial_web(arr, lay, matrix, space_f, WEB_A)
    return finish(arr, lay, matrix)


def concept_b(lay, matrix, fig, mask, body):
    """The body's movement ripples outward through the code as fascial contour rings."""
    sil = (body > .5).astype(np.uint8)
    dist = cv2.distanceTransform(1 - sil, cv2.DIST_L2, 5)
    smooth = cv2.GaussianBlur(dist, (0, 0), M * 0.45)
    clear = M * 0.3                                                      # air around the body

    def module(r, c, cx, cy):
        dd = dist[int(cy), int(cx)]
        t = float(np.clip((dd - clear) / (5 * M), 0, 1))                 # 0 at the body, 1 far out
        h = M * (0.4 + 0.1 * t)                                           # 0.8 -> 1.0 of a module
        if t > .98:
            return [(cx - h, cy - h), (cx + h, cy - h), (cx + h, cy + h), (cx - h, cy + h)]
        return capsule(cx, cy, 2 * h, 2 * h, 0, steps=6) if t < .25 else             [(cx - h, cy - h), (cx + h, cy - h), (cx + h, cy + h), (cx - h, cy + h)]

    mods = module_layer(lay, matrix, lambda cx, cy: dist[int(cy), int(cx)] > clear, module)

    # fascial contour rings: iso-distance lines of the silhouette, fading outward
    rings = np.zeros((H, W), np.float32)
    half = 0.07 * M
    for k in range(7):
        level = clear + M * (0.55 + 1.35 * k)
        a = np.clip(1.5 - np.abs(smooth - level) / half, 0, 1) * (1 - k / 9)
        rings = np.maximum(rings, a)
    rings *= (1 - sil)

    curves = []
    for name, pts in LINES_BODY.items():
        head, tail = TAILS.get(name, ([], []))
        curves.append(head + pts + tail)
    spirals = draw_lines(lay, curves, 0.15 * M, MOSS)
    # small knockouts where lines cross light module centres: OpenCV binarises locally,
    # so even a light line through a centre can read dark
    knock = np.zeros((H, W), np.uint8)
    for r in range(lay.n):
        for c in range(lay.n):
            if not matrix[r][c]:
                cx, cy = lay.centre(r, c)
                cv2.circle(knock, (int(cx), int(cy)), int(M * KNOCK_R), 1, -1)
    knock = cv2.GaussianBlur(knock.astype(np.float32), (5, 5), 0)
    rings *= 1 - knock
    spirals *= 1 - knock * (1 - sil)

    lum = fig @ np.array([0.299, 0.587, 0.114], np.float32)
    duo = ramp(np.clip((lum - 20) / 225, 0, 1) ** 0.95)
    base = np.full((H, W, 3), IVORY, np.float32)
    arr = compose(base, [(rings, RING), (spirals * (1 - body), MOSS), (mods, FOREST), (body, duo),
                         (spirals * body, MOSS)])
    zone = cv2.GaussianBlur((dist <= clear).astype(np.float32), (3, 3), 0)
    arr = fascial_web(arr, lay, matrix, zone, WEB_B)
    return finish(arr, lay, matrix)


def main():
    OUT.mkdir(exist_ok=True)
    qr, matrix = qr_matrix()
    lay = Layout(len(matrix))
    fig, mask, body = load_figure(lay)
    outs = {}
    for key, fn in (("A", concept_a), ("B", concept_b)):
        img = fn(lay, matrix, fig, mask, body)
        img.save(OUT / f"movement-within-{key}.png")
        img.resize((1200, 1500), Image.LANCZOS).save(OUT / f"movement-within-{key}-1200.png")
        outs[key] = img
        print("wrote", OUT / f"movement-within-{key}.png")
    sheet = Image.new("RGB", (2 * 1200 + 120, 1500 + 80), (221, 213, 198))
    for i, key in enumerate("AB"):
        sheet.paste(outs[key].resize((1200, 1500), Image.LANCZOS), (40 + i * 1240, 40))
    sheet.save(OUT / "movement-within-compare.png")
    print(f"symbol: version {qr.version}-{qr.error}, mask {qr.mask}, {len(matrix)}x{len(matrix)}")


if __name__ == "__main__":
    main()
